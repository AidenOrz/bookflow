"""bookflow.fix — OCR 常见形近错的保守修正。

两类规则：
1. RULES：全局替换，只收录"错误写法在中文里根本不是词"的对子。
2. CTX_RULES：带否定前瞻/后顾的正则，处理「人/入」「己/已」这类
   两种写法都存在的混淆，用前后文排除正常用法（如「领导人」「容纳人」）。

两条硬约束（都是踩过坑之后加的）：
- **长串优先**：RULES 按模式长度降序应用，避免短规则先把长模式的前缀改掉。
- **只计净改动**：统计的是"文本真的变了的地方"，不是"规则命中次数"。
  历史上「己经→已经」+「自已经→自己经」互逆，导致「他自己经常」被记 2 处
  "修正"却净改动为 0，report.json 的数字因此系统性偏大。

宁可漏改不可错改：凡是拿不上下文证据的，一律只当 audit 候选，不自动改。
"""
import re

# 全局替换表：(错误写法, 正确写法)。只收"错误写法在中文里不是词"的对子。
RULES = [
    ("自已", "自己"),      # 已/己 混淆
    ("时侯", "时候"),
    ("即然", "既然"),
    ("按装", "安装"),
    ("年令", "年龄"),
    ("辩别", "辨别"),
    ("辨证法", "辩证法"),
]

# (正则, 替换, 说明)。每条都带排除条件。
CTX_RULES = [
    # 「进入」被认成「进人」：排除「进人的/进人们/进人民」「逃进人的…」等本当成立的结构
    (re.compile(r"进人(?!的|们|民|类|性|自己|家|口|眼|耳|手|心)"), "进入", "进人→进入"),
    # 「深入」被认成「深人」：深人不是词，但「深人静语」这类生僻写法按漏改处理
    (re.compile(r"深人(?![心静])"), "深入", "深人→深入"),
    # 「纳入」被认成「纳人」：排除「容纳人」「纳人情」
    (re.compile(r"(?<!容)纳人(?!情|们|的|心|性|家|员)"), "纳入", "纳人→纳入"),
    # 「入门」被认成「人门」：人门不是词
    (re.compile(r"人门"), "入门", "人门→入门"),
    # 「引入」被认成「引人」：排除成对的「引人+动词」结构
    (re.compile(r"引人(?![注目入胜深思瞩目注意关注发笑遐想不快侧目神往入彀])"),
     "引入", "引人→引入"),
    # 「收入」被认成「收人」：收人不是词，但「收人心」「收人钱财」是
    (re.compile(r"收人(?!心|情|钱财|员|马)"), "收入", "收人→收入"),
    # 「融入」被认成「融人」
    (re.compile(r"融人(?![们和的])"), "融入", "融人→融入"),
    # 「侵入」被认成「侵人」
    (re.compile(r"侵人(?!们|的)"), "侵入", "侵人→侵入"),
    # 由 audit.py 的词表校验确认的同类错误
    (re.compile(r"陷人(?!于|们|的|心)"), "陷入", "陷人→陷入"),
    (re.compile(r"输人(?!们|的|才|员)"), "输入", "输人→输入"),
    (re.compile(r"射人(?![先手马们])"), "射入", "射人→射入"),
    (re.compile(r"推祟"), "推崇", "推祟→推崇"),
    (re.compile(r"陶治(?![安])"), "陶冶", "陶治→陶冶"),
    (re.compile(r"异已"), "异己", "异已→异己"),
    # 「入口处」被认成「人口处」；但「中国人口处于…」是「人口+处于」，不能改
    (re.compile(r"人口处(?![于境])"), "入口处", "人口处→入口处"),
    # 「已经」被认成「己经」；但「自己经常」「知己经年」是「自/知己 + 经…」，必须排除
    (re.compile(r"(?<![自知己])己经(?!年|济|验|常)"), "已经", "己经→已经"),
    # 「辩证论」被认成「辨证论」，但「辨证论治」是中医标准术语，必须排除
    (re.compile(r"辨证论(?!治)"), "辩证论", "辨证论→辩证论"),
]


def apply(md, verbose=True):
    """返回 (修正后文本, 统计, 明细)。明细含每处修改的上下文。

    统计口径是**净改动**：只记录真正改变了文本的规则。
    """
    stat = {}
    detail = []

    # 长串优先，防止短规则吃掉长模式的前缀
    for bad, good in sorted(RULES, key=lambda kv: -len(kv[0])):
        if bad not in md:
            continue
        hits = list(re.finditer(re.escape(bad), md))
        for m in hits:
            detail.append({
                "rule": bad + "→" + good,
                "ctx": md[max(0, m.start() - 16):m.end() + 12].replace("\n", " "),
            })
        before = md
        md = md.replace(bad, good)
        if md != before:
            stat[bad + "→" + good] = len(hits)

    for pat, good, label in CTX_RULES:
        hits = list(pat.finditer(md))
        if not hits:
            continue
        for m in hits:
            detail.append({
                "rule": label,
                "ctx": md[max(0, m.start() - 16):m.end() + 12].replace("\n", " "),
            })
        before = md
        md = pat.sub(good, md)
        if md != before:          # 净改动才算数
            stat[label] = len(hits)

    if verbose:
        for k, v in stat.items():
            print("  修正 %-14s %d 处" % (k, v))
    return md, stat, detail
