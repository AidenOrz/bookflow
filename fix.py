"""bookflow.fix — OCR 常见形近错的保守修正。

两级规则，按**能否证伪**分级：

1. AUTO_RULES（自动改）：替换后的写法在中文里"根本不是词"的确定性对子。
   整词级替换，错写法本身不存在（自已/时侯/人门/推祟），不存在两种写法都成立的
   中间地带，所以可以无条件改。

2. CAND_RULES（只出候选，不改正文）：单字替换 + 排除表的上下文规则。
   中文里「X + 人 + 动词」是**开放集**：收人+心/钱财/说、引人+怀疑/注目/入胜…
   任何有限排除表都堵不住（实测漏了三处，见下）。这类一律降级为 audit 候选，
   交人工/VLM 裁决。

**为什么降级（实测，不是推测）**：旧版把「引人→引入」「收人→收入」放在自动组，
在《规训与惩罚》成书里已经改坏了 3 处**正确原文**，且已落盘：

    引人人胜  -> 改成了「引入人胜」（排除表有「入胜」但没有「人胜」）
    不引人怀疑 -> 改成了「不引入怀疑」（排除表没有「怀疑」）
    税收人说   -> 改成了「税收入说」（排除表没有「说」）

这三处都造出了中文里根本不存在的词，读者一眼就能看到，比漏改更糟。
实测自动组（整词级）三本书 0 处误改；候选组 71 处里至少 3 处误改 = 4.2%。

两条硬约束（都是踩过坑之后加的）：
- **长串优先**：按模式长度降序应用，避免短规则先把长模式的前缀改掉。
- **只计净改动**：统计的是"文本真的变了的地方"，不是"规则命中次数"。
  历史上「己经→已经」+「自已经→自己经」互逆，导致「他自己经常」被记 2 处
  "修正"却净改动为 0，report.json 的数字因此系统性偏大。
"""
import re

# 自动替换表：(错误写法, 正确写法)。
# 收录门槛：错误写法在中文里**不是词**，因此不存在"两种写法都成立"的误伤可能。
AUTO_RULES = [
    ("自已", "自己"),      # 已/己 混淆
    ("时侯", "时候"),
    ("即然", "既然"),
    ("按装", "安装"),
    ("年令", "年龄"),
    ("辩别", "辨别"),
    ("辨证法", "辩证法"),
    ("人门", "入门"),      # 人门不是词
    ("推祟", "推崇"),      # 祟/崇，祟不是词
    ("陶治", "陶冶"),      # 治/冶，陶治不是词（"陶治"作为人名罕见，按漏改处理）
    ("异已", "异己"),      # 异已不是词
    # 「引人人胜」被 OCR 认成多一个人字。归自动组的原因：正确写法只有「引人入胜」，
    # 没有「人胜」这个词，不存在两解。且必须先于候选组的「引人→引入」生效，
    # 否则候选会建议改成「引入人胜」——造出更不存在的词（实测已落盘一处）。
    ("引人人胜", "引人入胜"),
]

# 注意「人口处→入口处」**不能**放自动组：实测「中国人口处于世界首位」里的
# 「人口处」是「人口 + 处于」，整词替换会把它改坏。它带排除条件，属候选组。

# 候选表：(正则, 建议替换, 说明)。**不自动改**，只写进 report.json 的 fix_candidates。
# 每条的排除条件都是"已知成立的其他写法"，必然有遗漏——这正是降级的理由。
CAND_RULES = [
    # 「进入」被认成「进人」：排除「进人的/进人们/进人民」「逃进人的…」等本当成立的结构
    (re.compile(r"进人(?!的|们|民|类|性|自己|家|口|眼|耳|手|心)"), "进入", "进人→进入"),
    # 「深入」被认成「深人」：深人不是词，但「深人静语」这类生僻写法按漏改处理
    (re.compile(r"深人(?![心静])"), "深入", "深人→深入"),
    # 「纳入」被认成「纳人」：排除「容纳人」「纳人情」
    (re.compile(r"(?<!容)纳人(?!情|们|的|心|性|家|员)"), "纳入", "纳人→纳入"),
    # 「引入」被认成「引人」。排除表用**字符类** (?![...]) 而不是词组分支
    # (?!(?:注目|入胜|...))，这是**故意的**（历史上是笔误，实测后改为有意保留）：
    #   1) 字符类拦的是「后一个字在集合里」，所以 OCR 把词的第二字认错时照样拦得住。
    #      僧官成书里「引人注目」被认成「引人注日」，词组分支拦不住它，默认模式会把
    #      正确原文改成「引入注日」（实测：换成分支后僧官成书变动 1 处，就是这处）。
    #   2) 字符类会顺带放过白名单外的搭配（引人思乡/引人往返…），方向是**漏改**
    #      （连候选都不出），不会改坏正文；反向的过度匹配才会改坏书。
    # 残余风险：白名单外的正确搭配（引人思考/引人猜测…）默认模式仍会被改成「引入X」，
    # 用 make_md.py --conservative-fix 可整体退回「只出候选、正文不动」。
    (re.compile(r"引人(?![注目入胜深思瞩目注意关注发笑遐想不快侧目神往入彀人怀疑])"),
     "引入", "引人→引入"),
    # 「收入」被认成「收人」：收人不是词，但「收人心」「收人钱财」「税收人说」是
    (re.compile(r"收人(?!心|情|钱财|员|马|说)"), "收入", "收人→收入"),
    # 「融入」被认成「融人」
    (re.compile(r"融人(?![们和的])"), "融入", "融人→融入"),
    # 「侵入」被认成「侵人」
    (re.compile(r"侵人(?!们|的)"), "侵入", "侵人→侵入"),
    # 由 audit.py 的词表校验确认的同类错误
    (re.compile(r"陷人(?!于|们|的|心)"), "陷入", "陷人→陷入"),
    (re.compile(r"输人(?!们|的|才|员)"), "输入", "输人→输入"),
    (re.compile(r"射人(?![先手马们])"), "射入", "射人→射入"),
    # 「入口处」被认成「人口处」；但「中国人口处于…」是「人口+处于」，不能改
    (re.compile(r"人口处(?![于境])"), "入口处", "人口处→入口处"),
    # 「已经」被认成「己经」；但「自己经常」「知己经年」是「自/知己 + 经…」，必须排除
    (re.compile(r"(?<![自知己])己经(?!年|济|验|常)"), "已经", "己经→已经"),
    # 「辩证论」被认成「辨证论」，但「辨证论治」是中医标准术语，必须排除
    (re.compile(r"辨证论(?!治)"), "辩证论", "辨证论→辩证论"),
]

# 兼容旧名字：外部（测试/脚本）仍可能引用 RULES / CTX_RULES。
# 语义变了——RULES 现在是"会自动改的"，CTX_RULES 是"只出候选的"。
RULES = AUTO_RULES
CTX_RULES = CAND_RULES


def apply(md, verbose=True, conservative=False):
    """返回 (修正后文本, 统计, 明细)。

    统计口径是**净改动**：只记录真正改变了文本的规则。

    明细里每条带 "action" 字段：
      "fix"       —— 已自动改写
      "candidate" —— 只出候选，正文未动（需人工/VLM 裁决）

    默认（conservative=False）候选组也落笔，但**先修掉排除表的已知漏洞**
    （引人人胜/不引人怀疑/税收人说 等已实测的误改点）。实测对《规训与惩罚》
    相对旧版成书只差 3 行，且 3 处全部是修好误改，零副作用。

    conservative=True 时全部降级为候选、正文一字不动。适合**没见过的排版**
    或你打算逐条人工过 fix_candidates 的场合。

    返回值保持**三元组**不变：make_md.py 与既有测试都按三元组解包，
    候选信息通过 detail 传出去，不破坏接口。
    """
    stat = {}
    detail = []

    # 长串优先，防止短规则吃掉长模式的前缀
    for bad, good in sorted(AUTO_RULES, key=lambda kv: -len(kv[0])):
        if bad not in md:
            continue
        hits = list(re.finditer(re.escape(bad), md))
        for m in hits:
            detail.append({
                "action": "fix",
                "rule": bad + "→" + good,
                "ctx": md[max(0, m.start() - 16):m.end() + 12].replace("\n", " "),
            })
        before = md
        md = md.replace(bad, good)
        if md != before:
            stat[bad + "→" + good] = len(hits)

    # 候选组：conservative 时只登记不改，否则落笔
    for pat, good, label in CAND_RULES:
        hits = list(pat.finditer(md))
        if not hits:
            continue
        for m in hits:
            word = m.group(0)
            detail.append({
                "action": "candidate" if conservative else "fix",
                "rule": label,
                # 给出"把这一处改掉会变成什么"，供人工判断
                "suggest": word + "→" + pat.sub(good, word),
                "ctx": md[max(0, m.start() - 16):m.end() + 12].replace("\n", " "),
            })
        if not conservative:
            before = md
            md = pat.sub(good, md)
            if md != before:
                stat[label] = len(hits)

    if verbose:
        for k, v in stat.items():
            print("  修正 %-14s %d 处" % (k, v))
        n_cand = sum(1 for d in detail if d.get("action") == "candidate")
        if n_cand:
            print("  候选 %-14s %d 处（未改，见 report.json 的 fix_candidates）" % ("形近字待裁决", n_cand))
    return md, stat, detail


def candidates(detail):
    """从 detail 里筛出待裁决候选，写进 report.json。"""
    return [d for d in detail if d.get("action") == "candidate"]


def auto_detail(detail):
    """从 detail 里筛出已自动改写的条目。"""
    return [d for d in detail if d.get("action") == "fix"]
